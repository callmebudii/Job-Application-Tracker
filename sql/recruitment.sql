CREATE TABLE IF NOT EXISTS job_postings (
 id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 company TEXT NOT NULL, title TEXT NOT NULL, location TEXT NOT NULL,
 description TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS candidate_applications (
 id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 job_id INTEGER NOT NULL REFERENCES job_postings(id),
 candidate_name TEXT NOT NULL, email TEXT NOT NULL,
 cv_name TEXT NOT NULL, cv_data BYTEA NOT NULL,
 status TEXT NOT NULL DEFAULT 'APPLIED' CHECK(status IN ('APPLIED','INTERVIEW','REJECTED','OFFER')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(job_id, email)
);
